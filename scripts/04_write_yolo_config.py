#!/usr/bin/env python3
"""LEGACY (Week 1, synthetic fixture) — Write an Ultralytics YAML for the fixture.

Never writes configs/rdd2022.yaml (the tracked official dataset config).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.constants import CLASS_NAMES, CLASS_TO_ID, DEFAULT_SEED
from src.paths import default_rdd2022_config, legacy_fixture_processed_dir
from src.seed import set_seed


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Write YOLO dataset YAML for the legacy fixture.")
    p.add_argument("--processed-dir", type=str, default=str(legacy_fixture_processed_dir()))
    p.add_argument(
        "--out",
        type=str,
        default=str(legacy_fixture_processed_dir() / "rdd2022_week1_fixture.yaml"),
    )
    p.add_argument("--seed", type=int, default=DEFAULT_SEED)
    return p.parse_args()


def main() -> int:
    args = parse_args()
    set_seed(args.seed)

    processed = Path(args.processed_dir).resolve()
    splits = processed / "splits"
    train_list = splits / "train.txt"
    val_list = splits / "val.txt"
    test_list = splits / "test.txt"

    if not train_list.is_file() or not val_list.is_file():
        print(
            f"Missing split lists under {splits}.\n"
            "Run: python scripts/03_create_splits.py",
            file=sys.stderr,
        )
        return 1

    out = Path(args.out)
    if out.resolve() == default_rdd2022_config().resolve():
        print("Refusing to overwrite the tracked official configs/rdd2022.yaml.", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)

    # Absolute dataset root is required: Ultralytics mishandles `..` in relative
    # `path` values. train/val/test stay relative to that root.
    path_key = processed.as_posix()
    train_rel = "splits/train.txt"
    val_rel = "splits/val.txt"
    test_rel = "splits/test.txt" if test_list.is_file() else "splits/val.txt"

    names = {CLASS_TO_ID[c]: c for c in CLASS_NAMES}
    cfg = {
        "path": path_key,
        "train": train_rel,
        "val": val_rel,
        "test": test_rel,
        "nc": len(CLASS_NAMES),
        "names": names,
        "class_ids": dict(CLASS_TO_ID),
    }

    # Also write a portable sibling next to the data with path: .
    local_yaml = processed / "rdd2022.yaml"
    local_cfg = {
        "path": ".",
        "train": train_rel,
        "val": val_rel,
        "test": test_rel,
        "nc": len(CLASS_NAMES),
        "names": names,
        "class_ids": dict(CLASS_TO_ID),
    }

    header = (
        "# RDD2022 YOLO dataset configuration\n"
        "# Classes: D00=0, D10=1, D20=2, D40=3\n"
        "# Generated by scripts/04_write_yolo_config.py\n"
        "# `path` is absolute for Ultralytics reliability; train/val/test are relative.\n"
        f"# Portable copy also written to: {local_yaml.as_posix()}\n"
    )
    body = yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False)
    out.write_text(header + body, encoding="utf-8")
    local_yaml.write_text(
        "# Portable YOLO config (path relative to this file's directory)\n"
        + yaml.safe_dump(local_cfg, sort_keys=False, default_flow_style=False),
        encoding="utf-8",
    )
    print(f"Wrote {out}")
    print(f"Wrote {local_yaml}")
    print(yaml.safe_dump(cfg, sort_keys=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
